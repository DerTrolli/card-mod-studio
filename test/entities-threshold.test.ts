/**
 * Threshold Colors on the entities card (v0.11): offered for the card frame
 * only — Background, Text colour, Border colour. Pins the caps, the write →
 * read round trip of every Studio-written shape, and that a style written by
 * an earlier version (where such a rule could only be hand-written, or sat in
 * a hidden module's state) loads and saves unchanged.
 */
import { describe, it, expect, afterEach, beforeEach } from 'vitest';
import { capsFor, thresholdPropertyAllowed } from '../src/utils/card-caps.js';
import { applyStudioState, buildMergedStudioState } from '../src/editor/studio-state.js';
import { generateCss } from '../src/generator/css-generator.js';
import { DEFAULT_THRESHOLD, DEFAULT_FONT, DEFAULT_BACKGROUND, DEFAULT_BORDER } from '../src/parser/state-mapper.js';
import { installEngines, restoreEngines, cfg } from './v010-audit-helpers.js';
import type { StudioState, ThresholdModuleState, ThresholdProperty } from '../src/types/index.js';

beforeEach(() => installEngines(['card-mod']));
afterEach(() => restoreEngines());

const card = (style?: string, extra: Record<string, unknown> = {}) =>
  cfg({ type: 'entities', title: 'Home', entities: ['light.a', 'sensor.b'], ...extra, ...(style ? { card_mod: { style } } : {}) });

const FRAME: ThresholdProperty[] = ['background', 'text-color', 'border-color'];

const threshold = (patch: Partial<ThresholdModuleState>): ThresholdModuleState => ({
  ...DEFAULT_THRESHOLD,
  enabled: true,
  entityId: 'sensor.t',
  rules: [{ id: 'r1', operator: '>', value: 25, color: '#ff0000' }, { id: 'r2', operator: '<', value: 10, color: '#0000ff' }],
  defaultColor: '#00ff00',
  colorStops: [{ id: 's1', value: 0, color: '#0000ff' }, { id: 's2', value: 50, color: '#ff0000' }],
  ...patch,
});

/** What a save-and-reopen must give back (ids are regenerated by the parser). */
const essence = (t: ThresholdModuleState) => ({
  enabled: t.enabled,
  entityId: t.entityId,
  attribute: t.attribute || '',
  valueMode: t.valueMode,
  properties: [...t.properties].sort(),
  borderWidth: t.properties.includes('border-color') ? t.borderWidth ?? 2 : undefined,
  ...(t.valueMode === 'gradient'
    ? { stops: t.colorStops.map((s) => [s.value, s.color]) }
    : { rules: t.rules.map((r) => [r.operator, r.value, r.color]), defaultColor: t.defaultColor }),
});

const saved = (state: StudioState, config = card()) => applyStudioState(state, config);
const reopened = (config: ReturnType<typeof card>) => buildMergedStudioState(config);
const blank = (): StudioState => reopened(card());

describe('caps: Threshold on the entities card', () => {
  it('the module is shown, Icon Color and Accent stay off', () => {
    const c = capsFor('entities');
    expect(c.modules.threshold).toBe(true);
    expect(c.modules.iconColor).toBe(false);
    expect(c.modules.accentColor).toBe(false);
  });

  it('offers exactly Background, Text colour and Border colour', () => {
    for (const p of FRAME) expect(thresholdPropertyAllowed(p, 'entities'), p).toBe(true);
    expect(thresholdPropertyAllowed('icon-color', 'entities')).toBe(false);
    expect(thresholdPropertyAllowed('accent-color', 'entities')).toBe(false);
  });

  it('heading still has none', () => {
    expect(capsFor('heading').modules.threshold).toBe(false);
  });
});

describe('Studio-written card-level thresholds on entities round-trip', () => {
  const propSets: ThresholdProperty[][] = [['background'], ['text-color'], ['border-color'], FRAME];
  for (const valueMode of ['switch', 'gradient'] as const) {
    for (const attribute of ['', 'battery']) {
      for (const properties of propSets) {
        it(`${valueMode}${attribute ? ' (attribute)' : ' (state)'} → ${properties.join('+')}`, () => {
          const t = threshold({ valueMode, attribute, properties, borderWidth: 3 });
          const written = saved({ ...blank(), threshold: t });
          const css = written.card_mod!.style as string;
          expect(css).toContain(attribute ? "state_attr('sensor.t', 'battery')" : "states('sensor.t')");
          expect(css).not.toContain('config.entity');
          const back = reopened(written);
          expect(essence(back.threshold)).toEqual(essence(t));
          // nothing leaks into Advanced CSS or another module, and a second save is byte-identical
          expect(back.advanced.rawCss).toBe('');
          expect(back.background.enabled).toBe(false);
          expect(back.border.enabled).toBe(false);
          expect(back.font.enabled).toBe(false);
          expect(saved(back, written).card_mod!.style).toBe(css);
        });
      }
    }
  }

  it('an entity-less card with no source picked writes nothing (the user must pick one)', () => {
    const css = generateCss({ ...blank(), threshold: threshold({ entityId: '', properties: FRAME }) }, 'entities', { config: card() });
    expect(css).toBe('');
  });

  it('keeps the card\'s rows and the other modules beside it', () => {
    const state: StudioState = {
      ...blank(),
      threshold: threshold({ properties: ['background'] }),
      border: { ...DEFAULT_BORDER, enabled: true, borderRadius: 12, borderWidth: 0, borderColor: '#123456' },
    };
    const written = saved(state);
    const back = reopened(written);
    expect(essence(back.threshold)).toEqual(essence(state.threshold));
    expect(back.border.enabled).toBe(true);
    expect(written.entities).toEqual(['light.a', 'sensor.b']);
  });
});

describe('styles from earlier versions load and save unchanged on entities', () => {
  const rule = (prop: string) => `${prop}: {{ 'red' if states('sensor.t') | float(0) > 5 else 'blue' }};`;
  const handWritten: Array<[string, string]> = [
    ['background', `ha-card {\n  ${rule('background')}\n}`],
    ['border shorthand', `ha-card {\n  ${rule('border: 2px solid').replace('border: 2px solid:', 'border: 2px solid')}\n}`],
    ['background on an attribute', "ha-card {\n  background: {{ 'red' if state_attr('sensor.t', 'battery') | float(0) < 20 else 'blue' }};\n}"],
    // own-entity / other-entity on-off templates are the Background module's, not Threshold's
    ['on/off background on another entity', "ha-card {\n  background: {{ 'red' if is_state('light.a', 'on') else 'blue' }};\n}"],
    ['on/off background on config.entity (Advanced CSS, never rewritten)', "ha-card {\n  background: {{ 'red' if is_state(config.entity, 'on') else 'blue' }};\n}"],
    ['static colours', 'ha-card {\n  background: #112233;\n  border: 1px solid #445566;\n}'],
  ];
  for (const [label, style] of handWritten) {
    it(`${label}: first save after a no-op reopen keeps the text`, () => {
      const config = card(style);
      const back = reopened(config);
      const again = saved(back, config);
      // Same declarations, same values — only whitespace between blocks may be normalised.
      const norm = (s: string) => s.replace(/\s+/g, ' ').trim();
      expect(norm(again.card_mod!.style as string)).toBe(norm(style));
      // …and it is stable from then on.
      const third = saved(reopened(again), again);
      expect(third.card_mod!.style).toBe(again.card_mod!.style);
    });
  }

  it('a hand-written block of another selector keeps its declarations next to a threshold', () => {
    const style = `ha-card {\n  ${rule('background')}\n}\n\n.card-content {\n  color: red;\n}`;
    const config = card(style);
    const back = reopened(config);
    expect(back.threshold.properties).toEqual(['background']);
    const out = saved(back, config).card_mod!.style as string;
    expect(out).toContain(rule('background'));
    expect(out).toContain('.card-content {\n  color: red;\n}');
  });

  it('hand-written state / attribute rules are adopted by the Threshold module', () => {
    const state = reopened(card(`ha-card {\n  ${rule('background')}\n}`));
    expect(state.threshold.enabled).toBe(true);
    expect(state.threshold.entityId).toBe('sensor.t');
    expect(state.threshold.properties).toEqual(['background']);
    expect(state.advanced.rawCss).toBe('');
  });

  it('a hand-written colour rule gets the title-colour companion on save, like Font colour on entities', () => {
    const style = `ha-card {\n  ${rule('color')}\n}`;
    const written = saved(reopened(card(style)), card(style)).card_mod!.style as string;
    expect(written).toContain(rule('color'));
    expect(written).toContain('--ha-card-header-color:');
  });

  it('on/off templates stay out of Threshold and keep their text', () => {
    const state = reopened(card("ha-card {\n  background: {{ 'red' if is_state(config.entity, 'on') else 'blue' }};\n}"));
    expect(state.threshold.enabled).toBe(false);
  });
});

describe('Text colour: Threshold beats Font colour on the card', () => {
  it('the Threshold colour is written, Font keeps its other settings, only one `color` reaches ha-card', () => {
    const state: StudioState = {
      ...blank(),
      font: { ...DEFAULT_FONT, enabled: true, fontSize: 18, color: '#00aa00' },
      threshold: threshold({ properties: ['text-color'] }),
    };
    const css = generateCss(state, 'entities', { config: card() });
    expect(css).toContain('font-size');
    expect(css).not.toContain('#00aa00');
    expect(css.match(/^\s*color:/gm)).toHaveLength(1);
    expect(css).toContain("color: {{ '#ff0000' if states('sensor.t')");
  });

  it('Background / Border modules step aside for a Threshold on the same property', () => {
    const state: StudioState = {
      ...blank(),
      background: { ...DEFAULT_BACKGROUND, enabled: true, color1: '#abcdef' },
      border: { ...DEFAULT_BORDER, enabled: true, borderWidth: 2, borderColor: '#654321' },
      threshold: threshold({ properties: ['background', 'border-color'] }),
    };
    const css = generateCss(state, 'entities', { config: card() });
    expect(css).not.toContain('#abcdef');
    expect(css).not.toContain('#654321');
  });
});
